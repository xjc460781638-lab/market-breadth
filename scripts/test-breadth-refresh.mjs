import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
let source=ts.transpileModule(fs.readFileSync(new URL('../lib/breadth-refresh.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
source=source.replace('"zod"',JSON.stringify(import.meta.resolve('zod'))).replace('"./breadth"',JSON.stringify(new URL('../lib/breadth.ts',import.meta.url).href));
const {basisSchema,calculateRefresh,parseBreadthQuote,roundPercent}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const fixture=JSON.parse(fs.readFileSync(0,'utf8'));
const basis=basisSchema.parse(fixture.basis);
const result=calculateRefresh(basis,fixture.quotes,new Date(basis.day+'T02:00:00Z'));
for(let i=0;i<250;i++) for(const code of Object.keys(result.rows[i].values)) assert.deepEqual(result.rows[i].values[code],fixture.expected.rows[i].values[code],`${result.rows[i].date} ${code}`);
assert.equal(result.eligibleStocks,fixture.expected.eligibleStocks);
assert.equal(roundPercent(1,8),12);assert.equal(roundPercent(3,8),38);
assert.throws(()=>calculateRefresh(basis,[]),/1000/);
const now=Date.parse(basis.day+'T02:00:00Z');
const raw={f12:'000001',f2:10,f18:9,f124:now/1000};
assert.ok(parseBreadthQuote(raw,basis.day,now));
for(const value of [null,'-',0,NaN,Infinity]) assert.equal(parseBreadthQuote({...raw,f2:value},basis.day,now),null);
assert.equal(parseBreadthQuote({...raw,f124:now/1000-601},basis.day,now),null);
assert.equal(parseBreadthQuote({...raw,f124:now/1000+301},basis.day,now),null);
assert.equal(parseBreadthQuote(raw,'2020-01-01',now),null);
console.log(`PASS: Python/TypeScript exact parity for 250 days, 31 industries, market, sum, ${result.eligibleStocks} eligible stocks; missing quotes, ex-rights mismatch, stale quotes and ties`);

const afterClose=Date.parse(basis.day+'T18:00:00+08:00');
const closeStamp=Date.parse(basis.day+'T15:00:00+08:00')/1000;
assert.ok(parseBreadthQuote({...raw,f124:closeStamp},basis.day,afterClose));
assert.equal(parseBreadthQuote({...raw,f124:closeStamp-60},basis.day,afterClose),null);
assert.equal(parseBreadthQuote({...raw,f124:closeStamp-86400},basis.day,afterClose),null);
assert.equal(calculateRefresh(basis,fixture.quotes,new Date(afterClose)).kind,'final');
console.log('PASS: after-close quote age, stale afternoon/morning rejection and final report classification');

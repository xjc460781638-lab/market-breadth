import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = ts.transpileModule(readFileSync(new URL('../lib/flow-refresh.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {quoteFromRow,mergeQuotes}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const now=new Date('2026-10-12T02:00:00Z');
const raw={f12:'BK1036',f13:90,f62:-123456789,f124:now.getTime()/1000};
assert.deepEqual(quoteFromRow(raw,now.getTime()),{code:'90.BK1036',time:'2026-10-12 10:00',net:-1.2346});
for(const invalid of [null,'-',NaN,Infinity]) assert.equal(quoteFromRow({...raw,f62:invalid}),null);
assert.equal(quoteFromRow({...raw,f124:now.getTime()/1000+600},now.getTime()),null);
const previous={resolution:'minute',asOf:'2026-10-09 15:00',times:['2026-10-09 15:00'],boards:[{code:'90.BK1036',values:[1],net:1,asOf:'2026-10-09 15:00'},{code:'90.BK1030',values:[2],net:2,asOf:'2026-10-09 15:00'}]};
assert.equal(mergeQuotes(previous,[]),null);
const quote=quoteFromRow(raw,now.getTime());
const next=mergeQuotes(previous,[quote],now);
assert.deepEqual(next.times,['2026-10-12 10:00']);
assert.deepEqual(next.boards.map(b=>b.net),[-1.2346,null]);
assert.deepEqual(next.boards[1].values,[null]);
const later=mergeQuotes(next,[{...quote,time:'2026-10-12 10:05',net:0}],now);
assert.deepEqual(later.boards[0].values,[-1.2346,0]);
assert.equal(mergeQuotes(later,[quote],now),null);
assert.equal(mergeQuotes({...previous,resolution:'close'},[{...quote,time:previous.asOf}]),null);
assert.equal(mergeQuotes(previous,[{...quote,code:'90.BK9999'}]),null);
assert.deepEqual(mergeQuotes(next,[quote],now).times,next.times);
console.log('PASS: units, missing values, future timestamps, day rollover, stale rejection, repeat refresh, curve alignment');
